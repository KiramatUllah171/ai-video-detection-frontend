export const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    const stored = localStorage.getItem(languageStorageKey)
    return languages.some((option) => option.code === stored) ? (stored as LanguageCode) : 'en'
  })

  const activeLanguage = languages.find((option) => option.code === language) ?? languages[0]

  useEffect(() => {
    localStorage.setItem(languageStorageKey, language)
    document.documentElement.lang = language
    document.documentElement.dir = activeLanguage.dir
  }, [activeLanguage.dir, language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    languages,
    setLanguage(nextLanguage) {
      if (nextLanguage === language) {
        return
      }

      localStorage.setItem(languageStorageKey, nextLanguage)
      setLanguageState(nextLanguage)
      window.setTimeout(() => window.location.reload(), 0)
    },
    t(key, values) {
      const activeTranslations = translations[language] as Record<string, string | undefined>
      const englishTranslations = translations.en as Record<string, string | undefined>
      const activeSupplementalTranslations = supplementalTranslations[language] as Record<string, string | undefined>
      const englishSupplementalTranslations = supplementalTranslations.en as Record<string, string | undefined>
      const template = activeSupplementalTranslations[key]
        ?? activeTranslations[key]
        ?? englishSupplementalTranslations[key]
        ?? englishTranslations[key]
        ?? key
      if (!values) {
        return template
      }

      return Object.entries(values).reduce(
        (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
        template,
      )
    },
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used inside LanguageProvider')
  }
  return context
}
